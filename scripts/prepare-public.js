import fs from "node:fs"
import path from "node:path"

const buildDir = path.resolve("build")
const publicDir = path.resolve("public")
const publicBuildDir = path.join(publicDir, "build")

if (!fs.existsSync(path.join(publicDir, "index.html"))) {
    throw new Error("public/index.html was not found.")
}

if (!fs.existsSync(path.join(buildDir, "index.js"))) {
    throw new Error("build/index.js was not generated by TypeScript.")
}

fs.rmSync(publicBuildDir, { recursive: true, force: true })
fs.cpSync(buildDir, publicBuildDir, { recursive: true })

console.log("Compiled files copied to public/build.")